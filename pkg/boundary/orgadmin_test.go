func TestAdminManagement(t *testing.T) {
	d := parse(t, adminDoc(t, boundary.OrgAdminManagement))
	got := sids(d)

	if slices.Contains(got, "DenyBoundaryPolicyEdit") {
		t.Error("the management admin may edit the boundary policies of its account")
	}

	for _, want := range []string{
		"AllowAll", "AllowOrganizationAdmin", "AllowBoundaryPolicyEdit", "DenyChangePermissionsSetsRoles",
		"DenyCreateOrChangeWithoutBoundary", "NoBoundaryDelete", "DenyDestructiveActions", "DenyDeletePulumiStateBuckets",
	} {
		if !slices.Contains(got, want) {
			t.Errorf("management admin lacks %s: %v", want, got)
		}
	}

	if slices.Contains(got, "DenyOrganizationAdmin") {
		t.Error("management admin denies organization administration")
	}

	for _, s := range d.Statement {
		if s.Sid == "AllowOrganizationAdmin" {
			want := []string{"organizations:*", "account:*", "sso:*", "sso-directory:*", "identitystore:*"}
			if !slices.Equal(actions(s.Action), want) {
				t.Errorf("org actions = %v", s.Action)
			}
		}
	}
}

func TestAdminMemberDeniesOrgAdminKeepsEverythingElse(t *testing.T) {
	off := parse(t, adminDoc(t, boundary.OrgAdminOff))
	member := parse(t, adminDoc(t, boundary.OrgAdminMember))

	// The member boundary is the default one plus exactly one statement, last.
	if len(member.Statement) != len(off.Statement)+1 || member.Statement[len(off.Statement)].Sid != "DenyOrganizationAdmin" {
		t.Fatalf("member statements: %v", sids(member))
	}

	if !slices.Equal(sids(off), sids(member)[:len(off.Statement)]) {
		t.Error("the member boundary changed the default statements")
	}

	for _, s := range member.Statement {
		if s.Sid == "DenyOrganizationAdmin" && s.Effect != "Deny" {
			t.Error("not a deny")
		}
	}
}

// match reports whether an IAM action pattern (with * and ?) matches an
// action, case-insensitively, as IAM does.
func match(pattern, action string) bool {
	p, a := strings.ToLower(pattern), strings.ToLower(action)

	var m func(p, a string) bool

	m = func(p, a string) bool {
		for len(p) > 0 {
			switch p[0] {
			case '*':
				for i := 0; i <= len(a); i++ {
					if m(p[1:], a[i:]) {
						return true
					}
				}

				return false
			case '?':
				if a == "" {
					return false
				}
			default:
				if a == "" || a[0] != p[0] {
					return false
				}
			}

			p, a = p[1:], a[1:]
		}

		return a == ""
	}

	return m(p, a)
}

func denied(patterns []string, action string) bool {
	for _, p := range patterns {
		if match(p, action) {
			return true
		}
	}

	return false
}

func memberDeny(t *testing.T) []string {
	t.Helper()

	for _, s := range parse(t, adminDoc(t, boundary.OrgAdminMember)).Statement {
		if s.Sid == "DenyOrganizationAdmin" {
			return actions(s.Action)
		}
	}

	t.Fatal("no DenyOrganizationAdmin")

	return nil
}

// The carve-outs are the reads PowerUserAccess grants outside its NotAction:
// organizations:DescribeOrganization, account:ListRegions and
// account:GetAccountInformation.
func TestMemberDenyCarveOuts(t *testing.T) {
	want := []string{"account:GetAccountInformation", "account:ListRegions", "organizations:DescribeOrganization"}
	if got := boundary.OrgAdminReadCarveOuts(); !slices.Equal(got, want) {
		t.Fatalf("carve-outs = %v", got)
	}

	deny := memberDeny(t)

	for _, a := range boundary.OrgAdminReadCarveOuts() {
		if denied(deny, a) {
			t.Errorf("%s is denied: the member admin loses a read it has today", a)
		}
	}
}

func TestMemberDenyCoversTheAdminActions(t *testing.T) {
	deny := memberDeny(t)

	for _, a := range []string{
		// organizations
		"organizations:CreateAccount", "organizations:CloseAccount", "organizations:AttachPolicy",
		"organizations:ListAccounts", "organizations:ListRoots", "organizations:DescribeAccount",
		"organizations:DescribePolicy", "organizations:DescribeOrganizationalUnit",
		"organizations:DescribeHandshake", "organizations:EnableAWSServiceAccess", "organizations:MoveAccount",
		"organizations:InviteAccountToOrganization", "organizations:LeaveOrganization",
		"organizations:DeleteOrganization", "organizations:UpdatePolicy", "organizations:TagResource",
		"organizations:RegisterDelegatedAdministrator", "organizations:DeregisterDelegatedAdministrator",
		// account
		"account:CloseAccount", "account:PutAlternateContact", "account:GetAlternateContact",
		"account:GetContactInformation", "account:GetPrimaryEmail", "account:EnableRegion",
		"account:DisableRegion", "account:StartPrimaryEmailUpdate", "account:AcceptPrimaryEmailUpdate",
		"account:PutAccountName", "account:ListAccountPolicies",
		// Identity Center and its directory
		"sso:CreatePermissionSet", "sso:ListInstances", "sso-directory:CreateUser", "identitystore:ListUsers",
		"identitystore:CreateGroup",
	} {
		if !denied(deny, a) {
			t.Errorf("%s is not denied in a member account", a)
		}
	}
}

func TestMemberDenyFitsTheBoundarySize(t *testing.T) {
	// A managed policy is at most 6144 characters without white space.
	for _, mode := range []boundary.OrgAdminMode{boundary.OrgAdminOff, boundary.OrgAdminMember, boundary.OrgAdminManagement} {
		if n := len(adminDoc(t, mode)); n > 6144 {
			t.Errorf("mode %q: %d bytes, over what IAM accepts for a managed policy", mode, n)
		}
	}
}

func TestPulumiStateBucketsStayProtectedInBothVariants(t *testing.T) {
	for _, mode := range []boundary.OrgAdminMode{boundary.OrgAdminMember, boundary.OrgAdminManagement} {
		doc := adminDoc(t, mode)
		for _, frag := range []string{`"s3:DeleteBucket"`, "arn:part:s3:::pulumi-state-*", `"cloudtrail:DeleteTrail"`, "role/AWSServiceRoleFor*", "aws-reserved/sso.amazonaws.com"} {
			if !strings.Contains(doc, frag) {
				t.Errorf("mode %q lost %s", mode, frag)
			}
		}
	}
}
