var update = flag.Bool("update", false, "rewrite the golden files")

type doc struct {
	Statement []struct {
		Sid       string
		Effect    string
		Action    any
		NotAction any
		Resource  any
	}
}

func adminDoc(t *testing.T, mode boundary.OrgAdminMode) string {
	t.Helper()

	s := spec()
	s.OrgAdmin = mode

	ps, err := boundary.Policies(s)
	if err != nil {
		t.Fatal(err)
	}

	for _, p := range ps {
		if p.Name == "bound@admin" {
			return p.Document
		}
	}

	t.Fatal("no admin boundary")

	return ""
}

func golden(t *testing.T, name, got string) {
	t.Helper()

	p := filepath.Join("testdata", name)

	if *update {
		if err := os.WriteFile(p, []byte(got+"\n"), 0o644); err != nil {
			t.Fatal(err)
		}
	}

	want, err := os.ReadFile(p)
	if err != nil {
		t.Fatal(err)
	}

	if got+"\n" != string(want) {
		t.Errorf("%s differs from the golden file (run with -update to rewrite it):\n%s", name, got)
	}
}

func parse(t *testing.T, s string) doc {
	t.Helper()

	var d doc
	if err := json.Unmarshal([]byte(s), &d); err != nil {
		t.Fatal(err)
	}

	return d
}

func sids(d doc) []string {
	var out []string
	for _, s := range d.Statement {
		out = append(out, s.Sid)
	}

	return out
}

func actions(a any) []string {
	switch v := a.(type) {
	case string:
		return []string{v}
	case []any:
		var out []string
		for _, x := range v {
			out = append(out, x.(string))
		}

		return out
	}

	return nil
}

// admin-default.json was generated by the code before OrgAdmin existed.
func TestAdminDefaultIsByteIdentical(t *testing.T) {
	want, err := os.ReadFile("testdata/admin-default.json")
	if err != nil {
		t.Fatal(err)
	}

	if got := adminDoc(t, boundary.OrgAdminOff); got+"\n" != string(want) {
		t.Errorf("the default admin boundary changed:\n%s", got)
	}

	if adminDoc(t, boundary.OrgAdminOff) != adminDoc(t, "") {
		t.Error("OrgAdminOff is not the zero value")
	}
}

func TestOtherShapesUnchangedByMode(t *testing.T) {
	base := spec()

	for _, mode := range []boundary.OrgAdminMode{boundary.OrgAdminMember, boundary.OrgAdminManagement} {
		s := spec()
		s.OrgAdmin = mode

		a, _ := boundary.Policies(base)
		b, _ := boundary.Policies(s)

		for i := range a {
			if a[i].Name != "bound@admin" && a[i] != b[i] {
				t.Errorf("mode %q changed %s", mode, a[i].Name)
			}
		}
	}
}

