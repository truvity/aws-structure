func cmdDrift(ctx context.Context, args []string, stdout io.Writer) error {
	fs := flags("drift")
	path := fs.String("registry", "", "registry file (required)")
	profile := fs.String("profile", "", "AWS profile of the management account (required)")
	ssoRegion := fs.String("sso-region", "", "Identity Center instance region (required)")
	fail := fs.Bool("fail", false, "exit 1 when there is drift")

	if err := fs.Parse(args); err != nil {
		return err
	}

	reg, err := loadRegistry(*path)
	if err != nil {
		return err
	}

	if *profile == "" || *ssoRegion == "" {
		return errors.New("-profile and -sso-region are required")
	}

	m := awsprofile.NewManager(slog.New(slog.DiscardHandler))

	mgmt, err := m.GetAWSConfig(ctx, *profile)
	if err != nil {
		return err
	}

	idc, err := m.GetAWSConfigWithRegion(ctx, *profile, *ssoRegion)
	if err != nil {
		return err
	}

	live, err := drift.Read(ctx, drift.Clients{
		Organizations:   organizations.NewFromConfig(mgmt),
		SSOAdmin:        ssoadmin.NewFromConfig(idc),
		IdentityStore:   identitystore.NewFromConfig(idc),
		InstanceARN:     reg.IdentityCenter.InstanceARN,
		IdentityStoreID: reg.IdentityCenter.IdentityStoreID,
	})
	if err != nil {
		return err
	}

	findings := drift.Compare(reg, live)
	for _, f := range findings {
		if _, err := fmt.Fprintln(stdout, f.String()); err != nil {
			return err
		}
	}

	if len(findings) == 0 {
		_, err = fmt.Fprintf(stdout, "drift: none (%d accounts, %d OUs, %d assignments)\n",
			len(live.Accounts), len(live.OUs), len(live.Assignments))

		return err
	}

	if *fail {
		return errFindings
	}

	return nil
}

func cmdAccessRoles(ctx context.Context, args []string, stdout io.Writer) error {
	fs := flags("access-roles")
	path := fs.String("registry", "", "registry file (required)")
	profile := fs.String("profile", "", "AWS profile of the management account (required)")
	role := fs.String("role", "OrganizationAccountAccessRole", "role assumed in each member account")
	partition := fs.String("partition", "aws", "ARN partition")
	out := fs.String("out", "", "write to this file instead of stdout")
	header := fs.String("header", "GENERATED by awsorgctl access-roles; regenerate instead of editing.", "comment written at the top")

	if err := fs.Parse(args); err != nil {
		return err
	}

	reg, err := loadRegistry(*path)
	if err != nil {
		return err
	}

	if *profile == "" {
		return errors.New("-profile is required")
	}

	m := awsprofile.NewManager(slog.New(slog.DiscardHandler))

	mgmt, err := m.GetAWSConfig(ctx, *profile)
	if err != nil {
		return err
	}

	mgmtID, err := m.GetAccountID(ctx, *profile)
	if err != nil {
		return err
	}

	accounts := map[string]string{}

	for _, a := range reg.Accounts {
		if a.ID != "" {
			accounts[a.Name] = a.ID
		}
	}

	stsClient := sts.NewFromConfig(mgmt)

	set, err := drift.AccessRoles(ctx, accounts, func(_ context.Context, id string) (drift.IAMAPI, error) {
		if id == mgmtID {
			return iam.NewFromConfig(mgmt), nil // the management account has no access role to assume
		}

		cfg := mgmt.Copy()
		cfg.Credentials = aws.NewCredentialsCache(stscreds.NewAssumeRoleProvider(stsClient,
			fmt.Sprintf("arn:%s:iam::%s:role/%s", *partition, id, *role)))

		return iam.NewFromConfig(cfg), nil
	})
	if err != nil {
		return err
	}

	data, err := drift.RenderAccessRoles(set, *header)
	if err != nil {
		return err
	}

	return write(*out, stdout, data)
}
